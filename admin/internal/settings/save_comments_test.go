// A save from the web UI used to drop every comment in config.yml: the ones
// config-init wrote beside each bootstrap value, and whatever the operator
// had noted about why a value is what it is.  The first save after install
// took them all.  Save now carries them onto the keys it writes again.
func TestSaveKeepsComments(t *testing.T) {
	dir := t.TempDir()
	p := filepath.Join(dir, "config.yml")
	orig := `# unmask config (generated by unmask config-init)
db:
  driver: sqlite
  sqlite_path: ` + filepath.Join(dir, "x.sqlite") + `
  # mariadb:
  #   host: 127.0.0.1
  #   port: 3306

secret:
  # _bv cookie HMAC key.  If leaked, change this.
  # sig_hash: sha256   # once every nginx runs a module that verifies both
  bv_secret: "0123456789abcdef0123456789abcdef"
  # math captcha token HMAC-SHA256 base
  captcha_secret_base: "fedcba9876543210"

server:
  bind: 127.0.0.1
  port: 9477   # the port the nginx upstream points at
  base_path: /unmask

events_retention_days: 7   # raised from the default on purpose: the hunt page is read weekly
`
	if err := os.WriteFile(p, []byte(orig), 0o600); err != nil {
		t.Fatal(err)
	}
	s, err := Load(p)
	if err != nil {
		t.Fatal(err)
	}
	s.EventsRetentionDays = 14
	if err := Save(s, p); err != nil {
		t.Fatal(err)
	}
	got, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}
	body := string(got)
	for _, want := range []string{
		"# unmask config (generated by unmask config-init)",
		"# mariadb:",
		"#   port: 3306",
		"# _bv cookie HMAC key.  If leaked, change this.",
		"# sig_hash: sha256   # once every nginx runs a module that verifies both",
		"# math captcha token HMAC-SHA256 base",
		"port: 9477 # the port the nginx upstream points at",
		"events_retention_days: 14 # raised from the default on purpose: the hunt page is read weekly",
	} {
		if !strings.Contains(body, want) {
			t.Errorf("saved config lost %q\n---\n%s", want, body)
		}
	}
	// The file had its own opening comment, so Save adds no header of its own.
	if strings.Contains(body, "managed by the unmask web UI") {
		t.Errorf("a file with its own opening comment must not get Save's header\n---\n%s", body)
	}
	if !strings.HasPrefix(body, "# unmask config (generated by unmask config-init)\n") {
		t.Errorf("the file's own opening comment must stay first\n---\n%s", body)
	}
	// And a second cycle keeps them again, once each.
	s2, err := Load(p)
	if err != nil {
		t.Fatal(err)
	}
	if err := Save(s2, p); err != nil {
		t.Fatal(err)
	}
	got2, _ := os.ReadFile(p)
	for _, want := range []string{"# mariadb:", "# math captcha token HMAC-SHA256 base", "# the port the nginx upstream points at"} {
		if n := strings.Count(string(got2), want); n != 1 {
			t.Errorf("after a second save %q occurs %d times, want 1\n---\n%s", want, n, got2)
		}
	}
}

// A file that begins with no comment gets Save's header, once: the header is
// a comment, so the next save keeps it as the file's own.
func TestSaveHeaderOnceOnAnUncommentedFile(t *testing.T) {
	dir := t.TempDir()
	p := filepath.Join(dir, "config.yml")
	if err := os.WriteFile(p, []byte("db:\n  driver: sqlite\n  sqlite_path: "+filepath.Join(dir, "x.sqlite")+"\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	for i := 0; i < 2; i++ {
		s, err := Load(p)
		if err != nil {
			t.Fatal(err)
		}
		if err := Save(s, p); err != nil {
			t.Fatal(err)
		}
		got, _ := os.ReadFile(p)
		if n := strings.Count(string(got), "managed by the unmask web UI"); n != 1 {
			t.Errorf("save %d: the header occurs %d times, want 1\n---\n%s", i+1, n, got)
		}
		if !strings.HasPrefix(string(got), "# unmask config") {
			t.Errorf("save %d: the header must open the file\n---\n%s", i+1, got)
		}
	}
}

// The header an earlier release's Save wrote said the comments were lost.
// Kept as the file's own comment it would say so forever; it is replaced.
func TestSaveReplacesTheOldHeader(t *testing.T) {
	dir := t.TempDir()
	p := filepath.Join(dir, "config.yml")
	orig := "# unmask config (= managed by unmask web UI; do not edit while admin running)\n" +
		"# Comments authored right after install are lost when saved via the web.\n" +
		"# Bootstrap values (= db/secret/server/...) are not web-editable; write them manually at install time only.\n\n" +
		"db:\n  driver: sqlite\n  sqlite_path: " + filepath.Join(dir, "x.sqlite") + "\n"
	if err := os.WriteFile(p, []byte(orig), 0o600); err != nil {
		t.Fatal(err)
	}
	s, err := Load(p)
	if err != nil {
		t.Fatal(err)
	}
	if err := Save(s, p); err != nil {
		t.Fatal(err)
	}
	got, _ := os.ReadFile(p)
	if strings.Contains(string(got), "are lost when saved") {
		t.Errorf("the old header must be replaced\n---\n%s", got)
	}
	if n := strings.Count(string(got), "managed by the unmask web UI"); n != 1 {
		t.Errorf("the new header occurs %d times, want 1\n---\n%s", n, got)
	}
}
