// Install wizard (= the first-run flow modeled after Cacti / Zabbix / Nextcloud).
//
// Right after start: any `/admin/*` access -> redirect to `/admin/setup/`
// if setup is needed.  After setup completes, hitting `/admin/setup/*`
// redirects to `/admin/` (= prevent re-setup).
//
// Steps:
//  1. welcome
//  2. choose DB driver (sqlite / mariadb) + connection test + save admin.yml + migration
//  3. create administrator account (= the first row in unmask_user)
//  4. done -> on to login
//
// setupNeeded() returns true when any of:
//   - h.DB == nil                (= initial start failed to connect)
//   - unmask_user table missing  (= migration not run)
//   - 0 users in the DB          (= no admin yet)
package handlers

