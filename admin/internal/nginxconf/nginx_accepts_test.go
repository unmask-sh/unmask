// TestNginxAcceptsTheRender runs a real nginx over what Render writes.
//
// The renderer's other tests read the output as text; whether nginx takes it
// is a different question, and the one an operator meets -- `nginx -t` fails
// on the next reload, or nginx does not come back after a restart.  Each case
// is a config.yml the admin's forms can produce, or one a hand edit can (the
// file is not validated on load), that once made nginx refuse the whole
// configuration.
//
// Skipped unless UNMASK_TEST_NGINX names an nginx binary that has the unmask
// module -- compiled in, or as the .so UNMASK_TEST_NGINX_MODULE names:
//
//	UNMASK_TEST_NGINX=/path/to/objs/nginx \
//	UNMASK_TEST_NGINX_MODULE=/path/to/objs/ngx_http_unmask_module.so \
//	    go test -run TestNginxAcceptsTheRender ./internal/nginxconf/
//
// The cases that render the compose flow are skipped on an nginx older than
// the flow needs; the rest run on every supported version, the oldest
// included.
func TestNginxAcceptsTheRender(t *testing.T) {
	bin := os.Getenv("UNMASK_TEST_NGINX")
	if bin == "" {
		t.Skip("UNMASK_TEST_NGINX is not set")
	}
	vOut, err := exec.Command(bin, "-v").CombinedOutput()
	if err != nil {
		t.Fatalf("%s -v: %v\n%s", bin, err, vOut)
	}
	composeOK, version, ok := parseNginxDryRun(string(vOut))
	if !ok {
		t.Fatalf("no version in %q", vOut)
	}
	t.Logf("nginx %s (compose flow: %v)", version, composeOK)

	ipja4 := "# generated by unmask communitybans. DO NOT EDIT.\n\"203.0.113.58:t13d1516h2_8daaf6152771_02713d6af862\" 1;\n"
	cases := []acceptCase{
		{name: "defaults"},
		{name: "defaults-compose", compose: true},
		{name: "defaults-host-map", hostMapBlock: true},
		// Monitor mode's map was volatile on every install; nginx before
		// 1.11.7 does not know the word.
		{name: "monitor-mode", yaml: `
challenge:
  default:
    observe_only: true
`},
		{name: "monitor-mode-compose", compose: true, yaml: `
challenge:
  default:
    observe_only: true
`},
		// An axis row's burst of 0 reached protect.inc as burst=0.
		{name: "axis-burst-zero", yaml: `
rate_limit:
  ja4_limit:
    enabled: true
    requests_per_min: 600
    burst: 0
`},
		// A per-site rule's Site keys host maps: a word map reserves, a
		// trailing backslash, a quote.
		{name: "site-default", yaml: `
nginx:
  bypass_paths:
    paths:
      - path: "^/api/"
        site: "default"
`},
		{name: "site-include", yaml: `
nginx:
  bypass_paths:
    paths:
      - path: "^/api/"
        site: "include"
`},
		{name: "site-backslash", yaml: `
nginx:
  honeypot:
    urls:
      - path: "^/trap-zz"
        site: 'shop.example.com\'
`},
		{name: "site-quote", yaml: `
nginx:
  bypass_paths:
    paths:
      - path: "^/internal-zz/"
        site: 'shop.example.com"'
`},
		// A host name of 47 characters or more does not fit nginx's default
		// map_hash_bucket_size.
		{name: "site-long-host", yaml: `
nginx:
  protected_paths:
    paths:
      - path: "^/login"
        site: "very-long-subdomain-name.marketing.example-company.co.jp"
`},
		{name: "site-long-host-community-bans", yaml: `
community_bans:
  subscribe_mode: fetch_apply
nginx:
  protected_paths:
    paths:
      - path: "^/login"
        site: "very-long-subdomain-name.marketing.example-company.co.jp"
`},
		// One promoted ip|ja4 ban is a 49-character key.
		{name: "community-bans-ipja4", yaml: `
community_bans:
  subscribe_mode: fetch_apply
`, files: map[string]string{"community-bans-ipja4.map": ipja4}},
		// A trusted-LB id and a custom rule's host or fingerprint are map
		// keys too.
		{name: "lb-id-default", yaml: `
nginx:
  trusted_lb_extra:
    - id: "default"
      cidrs: ["10.0.0.0/8"]
      header: "$http_x_client_ja4"
`},
		{name: "custom-rule-host-default", yaml: `
nginx:
  custom_rules:
    - id: cr1
      enabled: true
      action: captcha_only
      conditions:
        - kind: host
          values: ["default", "shop.example.com"]
    - id: include
      enabled: true
      action: deny
      conditions:
        - kind: ja4
          values: ["default", "t13d1516h2_*"]
`},
		{name: "custom-rule-host-default-compose", compose: true, yaml: `
nginx:
  custom_rules:
    - id: cr1
      enabled: true
      action: captcha_only
      rate_per_min: 30
      conditions:
        - kind: host
          values: ["default"]
`},
		// A bypass row of one's own that passes GET / HEAD / OPTIONS only:
		// for every site, and for one site alone.  A per-site row's map is
		// named after its host, and two hosts where one's name ends the
		// other's must each get their own.
		{name: "bypass-safe-methods", yaml: `
nginx:
  bypass_paths:
    paths:
      - path: "^/feed/"
        safe_methods_only: true
      - path: "^/shop-feed/"
        site: "example.com"
        safe_methods_only: true
      - path: "^/shop-feed/"
        site: "safe.example.com"
        safe_methods_only: true
      - path: "^/api/"
        site: "example.com"
`},
		// Every preset the tabs offer, switched on at once: a shipped pattern
		// has to compile in the engine of every nginx in the range.
		{name: "every-preset", mutate: everyPresetOn},
		{name: "every-preset-compose", compose: true, mutate: everyPresetOn},
	}
	for _, c := range cases {
		c := c
		t.Run(c.name, func(t *testing.T) {
			if c.compose && !composeOK {
				t.Skipf("nginx %s has no compose flow", version)
			}
			out, err := nginxTestRender(t, bin, c)
			if err != nil {
				t.Errorf("nginx refuses the render: %v\n%s", err, out)
			}
			// The module takes over a variable the configuration defines as
			// well and says so at notice level, which this test logs at.  The
			// render defines none of the module's variables itself; the one it
			// sets, $unmask_compose in protect.inc, is taken over by design and
			// without a word -- it used to be said at every nginx -t and reload.
			if strings.Contains(out, "is defined by the configuration as well") {
				t.Errorf("nginx -t reports a module variable the render defines too:\n%s", out)
			}
		})
	}
}

type acceptCase struct {
	name string
	yaml string // config.yml, beside the secret every case needs
	// hostMapBlock: the host's nginx.conf opens a map before it includes
	// http.inc (the stock websocket map), where map_hash_bucket_size can no
	// longer be set.
	hostMapBlock bool
	// compose: render the compose flow (nginx 1.17.6 and later).
	compose bool
	// files: written into the output directory after the render (the
	// community-bans maps are the daemon's to write, not the render's).
	files map[string]string
	// mutate: changes to the loaded settings that a fragment cannot say.
	mutate func(*settings.Settings)
}

// everyPresetOn switches on every preset group of the honeypot, protected
// path, bypass path and HTTPS-redirect exemption lists.
func everyPresetOn(s *settings.Settings) {
	for _, g := range HoneypotPresetGroups {
		s.Nginx.Honeypot.EnabledPresets = append(s.Nginx.Honeypot.EnabledPresets, g.ID)
	}
	for _, g := range ProtectedPathPresetGroups {
		s.Nginx.ProtectedPaths.EnabledPresets = append(s.Nginx.ProtectedPaths.EnabledPresets, g.ID)
	}
	for _, g := range BypassPathPresetGroups {
		s.Nginx.BypassPaths.EnabledPresets = append(s.Nginx.BypassPaths.EnabledPresets, g.ID)
	}
	s.Nginx.HTTPSRedirect = true
	for _, g := range RedirectExemptPresetGroups {
		s.Nginx.HTTPSRedirectExempt.EnabledPresets = append(s.Nginx.HTTPSRedirectExempt.EnabledPresets, g.ID)
	}
}

// nginxTestRender renders c into a fresh directory, wires the files into a
// minimal nginx.conf the way the install guide does, and returns what
// `nginx -t` said -- on its output and in the start-up log: what is logged
// while the configuration is parsed (a module's postconfiguration hook, say)
// goes to the compiled-in error log, <dir>/logs/error.log here, not to the
// error_log the configuration names.
func nginxTestRender(t *testing.T, bin string, c acceptCase) (string, error) {
	t.Helper()
	dir := t.TempDir()
	y := "secret:\n  bv_secret: \"0123456789abcdef0123456789abcdef\"\nnginx_log:\n  enabled: false\n" + c.yaml
	if !strings.Contains(c.yaml, "community_bans:") {
		y += "\ncommunity_bans:\n  subscribe_mode: \"off\"\n"
	}
	s, err := settings.LoadFromYAML(y)
	if err != nil {
		t.Fatalf("config.yml: %v", err)
	}
	if err := os.MkdirAll(filepath.Join(dir, "logs"), 0o755); err != nil {
		t.Fatal(err)
	}
	var b strings.Builder
	if mod := os.Getenv("UNMASK_TEST_NGINX_MODULE"); mod != "" {
		b.WriteString("load_module " + mod + ";\n")
	}
	b.WriteString("pid " + dir + "/nginx.pid;\nerror_log stderr notice;\nevents { worker_connections 64; }\nhttp {\n")
	for _, p := range []string{"client_body", "proxy", "fastcgi", "uwsgi", "scgi"} {
		b.WriteString("    " + p + "_temp_path " + dir + "/tmp-" + p + ";\n")
	}
	b.WriteString("    access_log off;\n")
	if c.hostMapBlock {
		b.WriteString("    map $http_upgrade $connection_upgrade { default upgrade; '' close; }\n")
	}
	b.WriteString("    include " + dir + "/http.inc;\n")
	b.WriteString("    include " + dir + "/upstream.conf;\n")
	b.WriteString("    include " + dir + "/forward-auth-lbtrust.conf;\n")
	b.WriteString("    server {\n        listen 127.0.0.1:18089;\n        server_name test.local;\n")
	b.WriteString("        include " + dir + "/server.inc;\n")
	b.WriteString("        location / {\n            include " + dir + "/protect.inc;\n            return 200 \"ok\\n\";\n        }\n")
	b.WriteString("    }\n}\n")
	hostConf := filepath.Join(dir, "nginx.conf")
	if err := os.WriteFile(hostConf, []byte(b.String()), 0o644); err != nil {
		t.Fatal(err)
	}
	s.Nginx.OutputDir = dir
	s.Nginx.ConfPath = hostConf
	if c.mutate != nil {
		c.mutate(&s)
	}
	SetDryRunSupported(c.compose)
	defer SetDryRunSupported(false)
	if err := Render(s, dir, "test"); err != nil {
		t.Fatalf("Render: %v", err)
	}
	for name, body := range c.files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	out, err := exec.Command(bin, "-t", "-p", dir, "-c", hostConf).CombinedOutput()
	if startup, rerr := os.ReadFile(filepath.Join(dir, "logs", "error.log")); rerr == nil && len(startup) > 0 {
		out = append(append(out, '\n'), startup...)
	}
	return strings.TrimSpace(string(out)), err
}

// TestNginxCompilesWhatCheckRegexAccepts holds the settings page's pattern
// check to the engine that runs the patterns.  CheckRegex compiles with Go's
// regexp and nginx with PCRE; a pattern Go takes and PCRE does not was
// "saved" and then failed the next `nginx -t`.  Every pattern below that
// CheckRegex accepts has to compile as a map's regex key in the nginx under
// test -- built with PCRE 1 at the old end of the range and PCRE 2 at the
// new, which disagree with each other too ([\w-.]).  What CheckRegex refuses
// is not this test's business; settings has its own list.
//
// Skipped like TestNginxAcceptsTheRender, unless UNMASK_TEST_NGINX is set.
func TestNginxCompilesWhatCheckRegexAccepts(t *testing.T) {
	bin := os.Getenv("UNMASK_TEST_NGINX")
	if bin == "" {
		t.Skip("UNMASK_TEST_NGINX is not set")
	}
	patterns := []string{
		// Escapes for one character.
		`^/\x{3042}`, `^/\x{41}`, `^/\x{ff}`, `^/\x{100}`, `^/\xff`, `\x{10FFFF}`, `[\x{100}-\x{200}]`, `\x{0100}`,
		`[\x{00e9}]`, `(?i)\x{e9}`, `\x41`, `\x{0041}`, `\377`, `\400`, `\777`, `[\400-\500]`, `\08`, `\12`, `\012`,
		"^/あ", "[あ-ん]",
		// Groups and flags.
		`(?P<uri>admin)`, `(?P<foo>admin)`, `(?<foo>admin)`, `(?P<http_x>a)`, `(?P<final_challenge>a)`, `(?P<n>a)|(?P<m>b)`,
		`(?:a|b)`, `(?i)abc`, `(?i:abc)`, `(?-i)abc`, `(?s)a.b`, `(?m)^a$`, `(?U)a+`,
		// Classes.
		`[\w-.]`, `[\w-]`, `[\w.-]`, `[^\w-.]`, `[\s-\d]`, `[\d-\s]`, `[[:alpha:]-z]`, `[[:alpha:]-]`, `[\pL-z]`, `[\p{L}-z]`,
		`[\d\-z]`, `[\x41-\x5a]`, `[\n-\r]`, `[a-z-9]`, `[\w-\.]`, `[\w+-.]`, `[.\w-]`, `[\D-a]`, `[\W-a]`, `[\S-a]`, `[\w-\d]`,
		`[+--]`, `[\d-]x`, `[^-\d]`, `[-\d]`, `[\d-\]]`, `[\w-. ]+@`, `[\t-z]`, `[\x{41}-z]`, `[\101-z]`, `[\--z]`, `[\.-z]`,
		`[a\d-z]`, `[\d-z\d-9]`, `[[:alpha:][:digit:]-]`, `[[:alpha:]\d-z]`, `[]a]`, `[^]a]`, `[]\w-.]`, `[[:word:]]+`, `[[:^alpha:]]`,
		`[[:ascii:]]`, `[\p{L}\d]`, `[\\d-z]`,
		// Unicode properties (the scripts every PCRE in the range knows).
		`\p{Greek}`, `\pL+`, `\P{Lu}`, `\pN`, `\pZ`, `\p{^L}`, `\p{Han}`, `\p{Latin}`, `\p{Cyrillic}`, `\p{L}`, `\p{Any}`,
		// The rest of the syntax the two share.
		`\z`, `\A/x`, `a\b`, `\Qa.b\E`, `\Q[\d-z]\E`, `\Q\x{3042}\E`, `a{2,5}`, `a{,5}`, `\$`, `\/`, `\-`, `\ `, `\d+`,
		`\\x{30}`, `^/(wp-admin|wp-login\.php)`, `(?i)(curl|wget|python-requests)/[\d.]+`,
	}
	accepted := 0
	for _, p := range patterns {
		if settings.CheckRegex(p) != nil {
			continue
		}
		accepted++
		dir := t.TempDir()
		if err := os.MkdirAll(filepath.Join(dir, "logs"), 0o755); err != nil {
			t.Fatal(err)
		}
		var b strings.Builder
		b.WriteString("pid " + dir + "/nginx.pid;\nerror_log stderr notice;\nevents { worker_connections 64; }\nhttp {\n")
		for _, tp := range []string{"client_body", "proxy", "fastcgi", "uwsgi", "scgi"} {
			b.WriteString("    " + tp + "_temp_path " + dir + "/tmp-" + tp + ";\n")
		}
		b.WriteString("    access_log off;\n    map $uri $unmask_test_p {\n        default 0;\n        \"~" + nginxQuote(p) + "\" 1;\n    }\n")
		b.WriteString("    server {\n        listen 127.0.0.1:18089;\n        location / { return 200 \"$unmask_test_p\"; }\n    }\n}\n")
		conf := filepath.Join(dir, "nginx.conf")
		if err := os.WriteFile(conf, []byte(b.String()), 0o644); err != nil {
			t.Fatal(err)
		}
		if out, err := exec.Command(bin, "-t", "-p", dir, "-c", conf).CombinedOutput(); err != nil {
			t.Errorf("CheckRegex accepts %s and nginx does not:\n%s", p, strings.TrimSpace(string(out)))
		}
	}
	// The list is no use if the check has grown to refuse most of it.
	if accepted < len(patterns)/2 {
		t.Errorf("CheckRegex accepted %d of %d patterns; the list no longer tests the engine", accepted, len(patterns))
	}
	t.Logf("%d of %d patterns pass CheckRegex, and nginx compiles each", accepted, len(patterns))
}
